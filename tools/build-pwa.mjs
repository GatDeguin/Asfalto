import fs from 'node:fs/promises';
import { createReadStream } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';
import assert from 'node:assert/strict';

const rootAt = process.argv.indexOf('--root');
const root = await fs.realpath(rootAt < 0 ? path.resolve(import.meta.dirname, '..') : path.resolve(process.argv[rootAt + 1]));
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const files = [], visited = new Set(), icons = new Set();
const shell = relative => relative === 'index.html' || relative === 'manifest.webmanifest' || relative === 'apple-touch-icon.png' || relative === 'assets/manifests/runtime.json' || icons.has(relative) || /\.(?:js|mjs|css|wasm|woff2?|ttf|otf)$/.test(relative) || /^(?:assets\/configuration\/|assets\/icons\/)/.test(relative);
const within = file => { const relative = path.relative(root, file); return relative !== '..' && !relative.startsWith(`..${path.sep}`) && !path.isAbsolute(relative); };
function localReference(value, base = 'index.html') {
  if (!value || /^(?:[a-z][a-z\d+.-]*:|\/\/|#)/i.test(value)) return null;
  const url = new URL(value.replaceAll('&amp;', '&'), new URL(base, 'https://asfalto-build.invalid/'));
  const relative = decodeURIComponent(url.pathname.slice(1));
  assert(within(path.resolve(root, relative)), `Reference escapes game: ${value}`);
  return relative || 'index.html';
}
const html = await fs.readFile(path.join(root, 'index.html'), 'utf8');
const references = [];
for (const tag of html.matchAll(/<[^>]+>/g)) {
  for (const attribute of tag[0].matchAll(/\b(?:href|src|poster|data-external-url)\s*=\s*["']([^"']+)["']/g)) {
    const relative = localReference(attribute[1]);
    if (relative) { references.push(relative); if (/\brel\s*=\s*["'][^"']*(?:icon|manifest)[^"']*["']/i.test(tag[0])) icons.add(relative); }
  }
}
async function visit(relative) {
  if (visited.has(relative) || relative === 'assets/manifests/release.json' || relative === 'sw.js') return;
  visited.add(relative);
  const absolute = path.join(root, relative), details = await fs.lstat(absolute);
  assert(!details.isSymbolicLink(), `PWA refuses symlinks: ${relative}`);
  if (details.isDirectory()) {
    for (const child of (await fs.readdir(absolute)).sort()) await visit(`${relative}/${child}`);
  } else if (details.isFile()) {
    const hash = createHash('sha256');
    for await (const chunk of createReadStream(absolute)) hash.update(chunk);
    files.push({ path: relative, bytes: details.size, sha256: hash.digest('hex'), shell: shell(relative) });
    if (relative.endsWith('.css')) {
      const css = await fs.readFile(absolute, 'utf8');
      for (const value of css.matchAll(/url\(\s*["']?([^"')]+)["']?\s*\)|@import\s+["']([^"']+)["']/g)) {
        const dependency = localReference((value[1] || value[2]).trim(), relative);
        if (dependency) await visit(dependency);
      }
    }
  }
}
for (const relative of ['index.html', 'manifest.webmanifest', 'apple-touch-icon.png', 'src', 'assets', 'tracks']) await visit(relative);
for (const relative of references) await visit(relative);
files.sort((a, b) => a.path < b.path ? -1 : a.path > b.path ? 1 : 0);
const release = {
  schema: 'asfalto-pwa/v1', id: sha(JSON.stringify(files)).slice(0, 20),
  totalBytes: files.reduce((sum, file) => sum + file.bytes, 0),
  shellBytes: files.filter(file => file.shell).reduce((sum, file) => sum + file.bytes, 0), files,
};
assert(release.shellBytes < 20_000_000, 'The automatic PWA shell exceeds the 20 MB budget');
const worker = `/* Generated by tools/build-pwa.mjs. Keep this worker URL stable. */\nconst ASFALTO_PWA_RELEASE=${JSON.stringify(release)};\n${await fs.readFile(path.join(root, 'src/runtime/pwa-worker.js'), 'utf8')}`;
const target = path.join(root, 'sw.js');
if (process.argv.includes('--check')) assert.equal(await fs.readFile(target, 'utf8'), worker, 'sw.js does not match this release; rebuild before the release inventory');
else await fs.writeFile(target, worker);
console.log(JSON.stringify({ status: 'pass', release: release.id, files: files.length, bytes: release.totalBytes, shellBytes: release.shellBytes }));
